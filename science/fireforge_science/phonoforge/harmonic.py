"""Harmonic phonons, quasi-harmonic Grüneisen parameters, Debye temperatures, sound
velocities and the Slack κ_l (phonon.harmonic / phonon.collect, phase8.md §4).

Plan (phonon.harmonic): the unit cell is the spglib standardized primitive cell of the
input (Structure.primitive()); the default supercell is 2×2×2 of that primitive cell
(24 atoms for a half-Heusler; images ≈ 8.6 Å apart at ZrNiSn's lattice constant — a
screening choice, pass `supercell` for more); finite displacements of `amplitude`
(0.01 Å) generated by phonopy for each volume V₀(1+ε), ε in `volume_strains`
(isotropic scaling of the primitive cell, fractional positions kept).

Analysis (phonon.collect), all on the reference volume (the strain closest to 0):
- DOS and frequencies on a Γ-centred `mesh` (default 20³), band structure along the
  Setyawan–Curtarolo path (pymatgen HighSymmKpath).
- min_freq_thz: lowest frequency on the mesh and the band path, excluding the three
  acoustic modes at Γ; dynamically_stable = min_freq_thz > −0.1 THz.
- θ_D (theta_d_k, used by Slack): second moment of the phonon DOS,
  θ_D = (h/k_B) √(5/3 ⟨f²⟩) (Grimvall), ⟨f²⟩ over all modes of the mesh (imaginary
  modes count as 0). Also reported: theta_d_debye_fit_k (phonopy's Debye fit of the
  low-frequency DOS) and theta_d_sound_k ((h/k_B) v_s (3n/4πV)^{1/3}).
- Sound velocities: acoustic frequencies at |q| = 1 % of the shortest reciprocal vector
  along Cartesian [100], [110], [111]: v = f/|q| (|q| without 2π). v_t = mean of the two
  lower branches, v_l = the upper; v_s = (⅓(1/v_l³ + 2/v_t³))^{−1/3} (Debye average).
- Mode Grüneisen γ_qj = −d ln ω/d ln V = −⟨e_qj|dD/d ln V|e_qj⟩/(2ω²_qj): dD(q)/d ln V
  is the least-squares slope of phonopy's dynamical matrices at the same reduced q over
  all volumes; eigenvectors from the reference volume (robust to band crossings; equal
  to the finite difference of ln ω for non-degenerate modes). Γ acoustic and imaginary
  modes are skipped. Averages: gruneisen_acoustic = mean over the three acoustic
  branches of each branch's RMS γ (sign of the mean kept) — used in Slack, since the
  Umklapp rate goes with γ²; gruneisen_acoustic_mean (plain mean); gruneisen_cv_<T>k
  (heat-capacity-weighted mean over all modes, the thermodynamic γ).
- Slack κ_l at `t_k` (slack.py) with θ_a = θ_D n^{−1/3}, δ = (V/n)^{1/3}, γ =
  gruneisen_acoustic (or the `gruneisen` parameter when only one volume was computed).
"""
from __future__ import annotations

import math
from typing import Any

import numpy as np

from ..model import SYMPREC, Structure
from . import slack
from .common import (STABILITY_THRESHOLD_THZ, PhononError, from_phonopy_atoms, jsonable,
                     light_json, quiet, stack_forces, to_phonopy_atoms)

H_PLANCK = 6.62607015e-34
KB = slack.KB
PLAN_FORMAT = "fireforge.phonon-plan.v1"
PHONON_FORMAT = "fireforge.phonon.v1"
DEFAULT_STRAINS = [-0.02, 0.0, 0.02]
BAND_POINTS = 31


def make_phonopy(unitcell: Structure, supercell_matrix, dataset: dict | None = None):
    from phonopy import Phonopy
    with quiet():
        ph = Phonopy(to_phonopy_atoms(unitcell), supercell_matrix=supercell_matrix,
                     primitive_matrix="P", symprec=SYMPREC)
    if dataset is not None:
        ph.dataset = _dataset_from_json(dataset)
    return ph


def _dataset_from_json(d: dict) -> dict:
    out = {"natom": int(d["natom"]), "first_atoms": []}
    for fa in d["first_atoms"]:
        out["first_atoms"].append({"number": int(fa["number"]),
                                   "displacement": np.asarray(fa["displacement"], dtype=float)})
    return out


def _dataset_to_json(d: dict) -> dict:
    return {"natom": int(d["natom"]),
            "first_atoms": [{"number": int(fa["number"]),
                             "displacement": [float(x) for x in fa["displacement"]]}
                            for fa in d["first_atoms"]]}


def ref_index(strains: list[float]) -> int:
    return int(np.argmin(np.abs(np.asarray(strains, dtype=float))))


# ---- plan -----------------------------------------------------------------------------

def build_plan(structure: Structure, *, supercell, volume_strains, amplitude: float,
               engine: str, preset: str) -> dict:
    """phonon.harmonic plan: per volume the unit cell, supercell matrix, phonopy
    displacement dataset and displaced supercells labelled v<i>.d<nnn>."""
    strains = [float(x) for x in volume_strains]
    if not strains or len(set(strains)) != len(strains):
        raise PhononError(f"volume_strains must be distinct values, got {volume_strains!r}")
    if any(s <= -0.5 or s >= 0.5 for s in strains):
        raise PhononError("volume strains must be within (-0.5, 0.5)")
    if not 0 < amplitude < 0.2:
        raise PhononError(f"amplitude must be in (0, 0.2) Å, got {amplitude}")
    prim = structure.primitive()
    volumes = []
    for i, eps in enumerate(strains):
        cell = prim.scaled(eps) if eps else prim.copy()
        ph = make_phonopy(cell, supercell)
        ph.generate_displacements(distance=amplitude)
        sc = []
        for j, a in enumerate(ph.supercells_with_displacements):
            sc.append({"label": f"v{i}.d{j + 1:03d}", "structure": light_json(from_phonopy_atoms(a))})
        volumes.append({"label": f"v{i}", "strain": eps, "unitcell": light_json(cell),
                        "volume_a3": cell.volume(), "supercell_matrix": supercell,
                        "dataset": _dataset_to_json(ph.dataset), "supercells": sc})
    return {"format": PLAN_FORMAT, "structure": structure.to_json(),
            "primitive": light_json(prim), "supercell_matrix": supercell,
            "amplitude_a": amplitude, "volume_strains": strains,
            "reference": ref_index(strains), "engine": engine, "preset": preset,
            "natom_supercell": len(ph.supercell), "volumes": volumes}


def plan_labels(plan: dict) -> list[str]:
    return [sc["label"] for v in plan["volumes"] for sc in v["supercells"]]


# ---- force constants ------------------------------------------------------------------

def volume_phonopy(vol: dict, forces_by_label: dict):
    """Phonopy object of one plan volume with symmetrized force constants."""
    cell = Structure.from_json(vol["unitcell"])
    ph = make_phonopy(cell, vol["supercell_matrix"], vol["dataset"])
    labels = [sc["label"] for sc in vol["supercells"]]
    ph.forces = stack_forces(forces_by_label, labels, len(ph.supercell))
    with quiet():
        ph.produce_force_constants(show_drift=False)
        ph.symmetrize_force_constants()
    return ph


# ---- analysis -------------------------------------------------------------------------

def _cv(f_thz: np.ndarray, t: float) -> np.ndarray:
    """Mode heat capacity in units of k_B (0 for f ≤ 0)."""
    f = np.clip(f_thz, 0.0, None) * 1e12
    x = H_PLANCK * f / (KB * t)
    with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
        c = np.where(x > 1e-8, x ** 2 * np.exp(x) / np.expm1(x) ** 2, 1.0)
    return np.where(f > 0, np.nan_to_num(c), 0.0)


def _band_path(prim: Structure):
    """(paths of reduced q in prim's reciprocal basis, labels) along the
    Setyawan–Curtarolo path; None if pymatgen cannot classify the lattice."""
    from pymatgen.symmetry.bandstructure import HighSymmKpath
    try:
        with quiet():
            kp = HighSymmKpath(prim.to_pymatgen(), path_type="setyawan_curtarolo")
    except Exception:                       # noqa: BLE001 - path is informational
        return None
    if not kp.kpath:
        return None
    rec_kp = kp.prim_rec.matrix / (2 * math.pi)         # rows, no 2π
    lat = prim.lattice_array

    def to_ours(frac_kp):
        cart = np.asarray(frac_kp) @ rec_kp
        return cart @ lat.T                              # q_frac = k_cart · L^T

    paths, labels = [], []
    for seg in kp.kpath["path"]:
        paths.append([to_ours(kp.kpath["kpoints"][n]).tolist() for n in seg])
        labels.extend(seg)
    return paths, ["Γ" if lb == "\\Gamma" else lb for lb in labels]


def _dispersion(ph, prim: Structure) -> dict | None:
    from phonopy.phonon.band_structure import get_band_qpoints_and_path_connections
    bp = _band_path(prim)
    if bp is None:
        return None
    paths, labels = bp
    qpts, conn = get_band_qpoints_and_path_connections(paths, npoints=BAND_POINTS)
    with quiet():
        ph.run_band_structure(qpts, path_connections=conn, labels=labels)
    bs = ph.band_structure
    return {"labels": labels, "path_connections": [bool(c) for c in conn],
            "qpoints": [np.round(q, 6).tolist() for q in bs.qpoints],
            "distances": [np.round(d, 6).tolist() for d in bs.distances],
            "frequencies_thz": [np.round(f, 5).tolist() for f in bs.frequencies]}


def _sound_velocities(ph, prim: Structure) -> dict:
    lat = prim.lattice_array
    rec = np.linalg.inv(lat).T                           # rows b_i, no 2π
    dq = 0.01 * float(np.linalg.norm(rec, axis=1).min())  # 1/Å
    dirs = np.array([[1, 0, 0], [1, 1, 0], [1, 1, 1]], dtype=float)
    dirs /= np.linalg.norm(dirs, axis=1)[:, None]
    q = (dirs * dq) @ lat.T
    with quiet():
        ph.run_qpoints(q)
    f = np.sort(ph.qpoints.frequencies, axis=1)[:, :3]   # THz
    v = f * 1e12 / (dq * 1e10)                           # m/s
    vt = float(v[:, :2].mean())
    vl = float(v[:, 2].mean())
    vs = (1.0 / 3.0 * (1.0 / vl ** 3 + 2.0 / vt ** 3)) ** (-1.0 / 3.0) if vt > 0 and vl > 0 else 0.0
    return {"v_l_m_s": vl, "v_t_m_s": vt, "v_s_m_s": float(vs),
            "per_direction": {"directions": ["100", "110", "111"],
                              "v_m_s": np.round(v, 2).tolist()}}


def _dynmat(ph, q) -> np.ndarray:
    ph.dynamical_matrix.run(q)
    return np.array(ph.dynamical_matrix.dynamical_matrix)


def mode_gruneisen(phs: list, ln_v: np.ndarray, ref: int, qpoints: np.ndarray) -> tuple:
    """(γ (nq, nmodes) with NaN where undefined, frequencies (nq, nmodes) THz at ref)."""
    x = ln_v - ln_v.mean()
    denom = float((x ** 2).sum())
    nq = len(qpoints)
    nb = 3 * len(phs[ref].primitive)
    gam = np.full((nq, nb), np.nan)
    freq = np.zeros((nq, nb))
    factor = phs[ref].unit_conversion_factor
    for iq, q in enumerate(qpoints):
        ds = [_dynmat(p, q) for p in phs]
        d0 = ds[ref]
        dd = sum(xi * (d - 0) for xi, d in zip(x, ds)) / denom   # least-squares slope
        w2, ev = np.linalg.eigh(d0)
        freq[iq] = np.sign(w2) * np.sqrt(np.abs(w2)) * factor
        gamma_pt = np.allclose(q, 0.0)
        for j in range(nb):
            if w2[j] <= 0 or (gamma_pt and j < 3) or freq[iq, j] < 0.05:
                continue
            e = ev[:, j]
            gam[iq, j] = -float(np.real(np.conj(e) @ dd @ e)) / (2.0 * w2[j])
    return gam, freq


def analyze(plan: dict, forces_by_label: dict, *, mesh: list[int], t_k: list[float],
            gruneisen_param: float | None = None) -> tuple[dict, Any]:
    """phonon.collect: returns (phonon JSON, reference-volume Phonopy with FCs)."""
    vols = plan["volumes"]
    ref = int(plan.get("reference", ref_index([v["strain"] for v in vols])))
    missing = [lb for lb in plan_labels(plan) if lb not in forces_by_label]
    if missing:
        raise PhononError(f"missing forces for {len(missing)} supercell(s): "
                          f"{', '.join(missing[:8])}{' ...' if len(missing) > 8 else ''}")
    phs =[volume_phonopy(v, forces_by_label) for v in vols]
    ph = phs[ref]
    prim = Structure.from_json(vols[ref]["unitcell"])
    n = prim.nsites
    vol = prim.volume()
    masses = np.asarray(ph.primitive.masses, dtype=float)

    # mesh (irreducible, Γ-centred) on every volume: min frequencies
    with quiet():
        for p in phs:
            p.run_mesh(mesh, is_gamma_center=True)
    qpts = np.asarray(ph.mesh.qpoints)
    weights = np.asarray(ph.mesh.weights, dtype=float)
    per_volume = []
    for v, p in zip(vols, phs):
        fr = np.asarray(p.mesh.frequencies)
        per_volume.append({"label": v["label"], "strain": v["strain"],
                           "volume_a3": float(v["volume_a3"]), "min_freq_thz": _min_freq(fr, qpts)})
    freqs = np.asarray(ph.mesh.frequencies)

    disp = _dispersion(ph, prim)
    min_f = _min_freq(freqs, qpts)
    if disp is not None:
        for qs, fs in zip(disp["qpoints"], disp["frequencies_thz"]):
            min_f = min(min_f, _min_freq(np.asarray(fs), np.asarray(qs)))
    stable = bool(min_f > STABILITY_THRESHOLD_THZ)

    # DOS, θ_D
    with quiet():
        ph.run_total_dos()
    dos = ph.total_dos
    fpos = np.clip(freqs, 0.0, None)
    f2 = float((weights[:, None] * fpos ** 2).sum() / (weights.sum() * freqs.shape[1]))
    theta_d = H_PLANCK * math.sqrt(5.0 / 3.0 * f2) * 1e12 / KB
    try:
        with quiet():
            dos.run_debye_frequency(n)
        theta_fit = float(dos.debye_frequency) * 1e12 * H_PLANCK / KB
    except Exception:                       # noqa: BLE001 - fit is informational
        theta_fit = float("nan")
    sound = _sound_velocities(ph, prim)
    vs = sound["v_s_m_s"]
    theta_sound = (H_PLANCK / KB * vs * (3.0 * n / (4.0 * math.pi * vol * 1e-30)) ** (1.0 / 3.0)
                   if vs > 0 else float("nan"))

    # Grüneisen
    grun: dict[str, Any] = {"source": None}
    gamma_used = None
    if len(phs) >= 2:
        ln_v = np.log([float(v["volume_a3"]) for v in vols])
        gam, _ = mode_gruneisen(phs, ln_v, ref, qpts)
        w = np.broadcast_to(weights[:, None], gam.shape)
        ok = ~np.isnan(gam)
        branch_rms, branch_mean = [], []
        for j in range(3):
            m = ok[:, j]
            if m.any():
                ww = weights[m]
                branch_rms.append(math.sqrt(float((ww * gam[m, j] ** 2).sum() / ww.sum())))
                branch_mean.append(float((ww * gam[m, j]).sum() / ww.sum()))
        ac_mean = float(np.mean(branch_mean)) if branch_mean else float("nan")
        ac_rms = float(np.mean(branch_rms)) if branch_rms else float("nan")
        g_ac = math.copysign(ac_rms, ac_mean) if branch_rms else float("nan")
        gall = np.where(ok, gam, 0.0)
        cv_avg = {}
        for t in [300.0] + [x for x in t_k if x != 300.0]:
            c = _cv(freqs, t) * w * ok
            cv_avg[f"{t:g}"] = float((c * gall).sum() / c.sum()) if c.sum() > 0 else float("nan")
        branch_avg = [float((w[:, j][ok[:, j]] * gam[ok[:, j], j]).sum() / w[:, j][ok[:, j]].sum())
                      if ok[:, j].any() else None for j in range(gam.shape[1])]
        grun = {"source": "qha", "gruneisen_acoustic": g_ac, "gruneisen_acoustic_mean": ac_mean,
                "gruneisen_acoustic_branch_rms": branch_rms,
                "gruneisen_cv": cv_avg, "gruneisen_branch_mean": branch_avg}
        gamma_used = g_ac
    if gruneisen_param is not None:
        grun["source"] = "parameter" if gamma_used is None else grun["source"]
        if gamma_used is None:
            gamma_used = float(gruneisen_param)

    # Slack
    theta_a = theta_d * n ** (-1.0 / 3.0)
    delta = (vol / n) ** (1.0 / 3.0)
    mbar = float(masses.mean())
    slack_out: dict[str, Any] = {"model": "slack", "t_k": list(t_k), "kappa_l_w_mk": None,
                                 "kappa_l_times_t_w_m": None, "gamma": gamma_used,
                                 "theta_a_k": theta_a, "delta_a": delta, "mean_mass_amu": mbar,
                                 "n_atoms": n, "note": ""}
    if gamma_used is None or not math.isfinite(gamma_used):
        slack_out["note"] = "no Grüneisen parameter (one volume and no `gruneisen` parameter)"
    elif gamma_used <= 0:
        slack_out["note"] = f"γ = {gamma_used:.3f} ≤ 0: Slack model not applicable"
    else:
        kw = dict(mean_mass_amu=mbar, theta_a_k=theta_a, delta_a=delta, n_atoms=n,
                  gamma=gamma_used)
        slack_out["kappa_l_w_mk"] = slack.slack_kappa(t_k, **kw)
        slack_out["kappa_l_times_t_w_m"] = slack.slack_kappa_times_t(**kw)
        slack_out["julian_a_w_mk"] = slack.julian_a_practical(gamma_used)

    out = {
        "format": PHONON_FORMAT,
        "formula": prim.reduced_formula(),
        "engine": plan.get("engine", ""), "preset": plan.get("preset", ""),
        "natoms_primitive": n, "volume_a3": vol, "mean_mass_amu": mbar,
        "supercell_matrix": plan["supercell_matrix"], "amplitude_a": plan["amplitude_a"],
        "mesh": list(mesh), "reference_volume": vols[ref]["label"],
        "min_freq_thz": min_f, "dynamically_stable": stable,
        "stability_threshold_thz": STABILITY_THRESHOLD_THZ,
        "max_freq_thz": float(freqs.max()),
        "theta_d_k": theta_d, "theta_d_debye_fit_k": theta_fit, "theta_d_sound_k": theta_sound,
        "theta_a_k": theta_a,
        "v_l_m_s": sound["v_l_m_s"], "v_t_m_s": sound["v_t_m_s"], "v_s_m_s": vs,
        "sound": sound["per_direction"],
        "gruneisen": gamma_used, "gruneisen_detail": grun,
        "slack": slack_out,
        "volumes": per_volume,
        "dos": {"frequency_thz": np.round(dos.frequency_points, 5).tolist(),
                "dos_states_per_thz": np.round(dos.dos, 6).tolist()},
        "dispersion": disp,
    }
    return jsonable(out), ph


def _min_freq(freqs: np.ndarray, qpts: np.ndarray) -> float:
    """Lowest frequency excluding the three acoustic modes at Γ."""
    f = np.atleast_2d(np.asarray(freqs, dtype=float)).copy()
    q = np.atleast_2d(np.asarray(qpts, dtype=float))
    at_g = np.all(np.abs(q - np.round(q)) < 1e-8, axis=1)
    f[at_g, :3] = np.inf
    return float(f.min())
